const CC2CONT = Object.fromEntries(Object.entries(CONT).flatMap(([k, v]) => v.split(' ').map((c) => [c, k])));
export function continentOf(cc, lon) {
  if (cc === 'RU') return lon > 60 ? 'Asia' : 'Europe';
  if (cc === 'US' && lon < -150) return 'Oceania'; // Hawaii
  if (cc === 'ES' && lon < -12) return 'Africa'; // Canary Islands
  return CC2CONT[cc] || 'Other';
}
